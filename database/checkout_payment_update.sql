-- Bổ sung schema cho checkout, voucher và thanh toán QR.
-- Chạy sau database/loopfit.sql nếu database hiện tại còn thiếu các cột này.

ALTER TABLE cart
    ADD COLUMN IF NOT EXISTS size VARCHAR(50) NULL,
    ADD COLUMN IF NOT EXISTS color VARCHAR(50) NULL,
    ADD COLUMN IF NOT EXISTS rent_date DATE NULL,
    ADD COLUMN IF NOT EXISTS return_date DATE NULL,
    ADD COLUMN IF NOT EXISTS price DECIMAL(10,2) DEFAULT 0,
    ADD COLUMN IF NOT EXISTS selected TINYINT(1) DEFAULT 1;

ALTER TABLE products
    ADD COLUMN IF NOT EXISTS deposit_price DECIMAL(10,2) DEFAULT 0,
    ADD COLUMN IF NOT EXISTS category VARCHAR(100) NULL,
    ADD COLUMN IF NOT EXISTS sizes VARCHAR(255) NULL,
    ADD COLUMN IF NOT EXISTS colors VARCHAR(255) NULL,
    ADD COLUMN IF NOT EXISTS rented_count INT DEFAULT 0;

ALTER TABLE promotions
    ADD COLUMN IF NOT EXISTS discount_amount DECIMAL(10,2) DEFAULT 0,
    ADD COLUMN IF NOT EXISTS max_discount DECIMAL(10,2) DEFAULT 0,
    ADD COLUMN IF NOT EXISTS min_order_amount DECIMAL(10,2) DEFAULT 0;

ALTER TABLE orders
    ADD COLUMN IF NOT EXISTS address_id INT NULL,
    ADD COLUMN IF NOT EXISTS deposit_amount DECIMAL(10,2) DEFAULT 0,
    ADD COLUMN IF NOT EXISTS total_rent DECIMAL(10,2) DEFAULT 0,
    ADD COLUMN IF NOT EXISTS total_deposit DECIMAL(10,2) DEFAULT 0,
    ADD COLUMN IF NOT EXISTS discount DECIMAL(10,2) DEFAULT 0,
    ADD COLUMN IF NOT EXISTS final_total DECIMAL(10,2) DEFAULT 0,
    ADD COLUMN IF NOT EXISTS payment_method VARCHAR(50) DEFAULT 'cash',
    ADD COLUMN IF NOT EXISTS payment_status VARCHAR(50) DEFAULT 'unpaid',
    ADD COLUMN IF NOT EXISTS notes TEXT NULL;

ALTER TABLE order_details
    ADD COLUMN IF NOT EXISTS size VARCHAR(50) NULL,
    ADD COLUMN IF NOT EXISTS color VARCHAR(50) NULL,
    ADD COLUMN IF NOT EXISTS rent_date DATE NULL,
    ADD COLUMN IF NOT EXISTS return_date DATE NULL,
    ADD COLUMN IF NOT EXISTS days INT DEFAULT 1,
    ADD COLUMN IF NOT EXISTS deposit DECIMAL(10,2) DEFAULT 0,
    ADD COLUMN IF NOT EXISTS subtotal DECIMAL(10,2) DEFAULT 0;
